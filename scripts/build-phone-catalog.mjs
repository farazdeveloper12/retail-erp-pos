// Builds supabase/seeds/phone-catalog.sql from the text files in
// supabase/catalog/*.txt (format: see supabase/catalog/README.md).
// Usage: node scripts/build-phone-catalog.mjs

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalogDir = join(root, "supabase", "catalog");
const outFile = join(root, "supabase", "seeds", "phone-catalog.sql");

function storageGb(text, where) {
  const value = text.trim().toUpperCase();
  const tb = /^(\d+)\s*TB$/.exec(value);
  if (tb) return Number(tb[1]) * 1024;
  const gb = /^(\d+)\s*(GB)?$/.exec(value);
  if (gb) return Number(gb[1]);
  throw new Error(`${where}: storage "${text}" is not valid`);
}

const models = [];
const seen = new Set();

for (const file of readdirSync(catalogDir).filter((f) => f.endsWith(".txt")).sort()) {
  const lines = readFileSync(join(catalogDir, file), "utf8").split(/\r?\n/);
  let brand = null;
  lines.forEach((raw, index) => {
    const where = `${file}:${index + 1}`;
    const line = raw.trim();
    if (!line || line.startsWith("//")) return;
    if (line.startsWith("#")) {
      brand = line.slice(1).trim();
      if (!brand) throw new Error(`${where}: empty brand`);
      return;
    }
    if (!brand) throw new Error(`${where}: model before any "# Brand" line`);
    const [name, year, variantText = "", colorText = ""] = line.split("|").map((p) => p.trim());
    if (!name) throw new Error(`${where}: missing model name`);
    if (name.length > 100) throw new Error(`${where}: model name longer than 100 characters`);
    const yearValue = year ? Number(year) : null;
    if (yearValue !== null && !(yearValue >= 2000 && yearValue <= 2100)) {
      throw new Error(`${where}: year "${year}" is not valid`);
    }

    const variants = [];
    for (const part of variantText.split(",").map((p) => p.trim()).filter(Boolean)) {
      const slash = part.split("/");
      if (slash.length === 2) {
        const ram = Number(slash[0]);
        if (!Number.isInteger(ram) || ram < 1 || ram > 64) throw new Error(`${where}: RAM "${part}" is not valid`);
        variants.push({ storage_gb: storageGb(slash[1], where), ram_gb: ram });
      } else {
        variants.push({ storage_gb: storageGb(part, where), ram_gb: null });
      }
    }
    const colors = [...new Set(colorText.split(",").map((c) => c.trim()).filter(Boolean))];
    for (const color of colors) {
      if (color.length > 60) throw new Error(`${where}: colour "${color}" longer than 60 characters`);
    }

    const key = `${brand.toLowerCase()}|${name.toLowerCase()}`;
    if (seen.has(key)) throw new Error(`${where}: ${brand} ${name} is listed twice`);
    seen.add(key);
    models.push({ brand, model: name, year: yearValue, variants, colors });
  });
}

const brands = new Set(models.map((m) => m.brand.toLowerCase()));
const variantCount = models.reduce((n, m) => n + m.variants.length, 0);
const colorCount = models.reduce((n, m) => n + m.colors.length, 0);
const json = JSON.stringify(models);
if (json.includes("$catalog$") || json.includes("$seed$")) {
  throw new Error("The data must not contain $catalog$ or $seed$");
}

const sql = `-- =============================================================================
-- Phone catalog seed (generated by scripts/build-phone-catalog.mjs; do not edit
-- by hand, edit supabase/catalog/*.txt and run the script again)
--
-- ${brands.size} brands, ${models.length} models, ${variantCount} storage/RAM options, ${colorCount} colours.
--
-- Idempotent: it only adds brands, models, storage/RAM options and colours that
-- are missing (names compared without case). Existing catalog rows are never
-- changed or removed. Safe to run more than once, on any project.
-- Everything runs in one DO block (one transaction): if any statement fails,
-- nothing is changed. It works as a single paste-and-run in the Supabase SQL
-- Editor (no temporary table that could disappear between statements).
-- =============================================================================

do $seed$
declare
  v_data jsonb := $catalog$${json}$catalog$::jsonb;
  v_brands integer;
  v_models integer;
  v_variants integer;
  v_colors integer;
begin
  if to_regclass('public.brands') is null or to_regclass('public.product_models') is null
     or to_regclass('public.model_variants') is null or to_regclass('public.model_colors') is null then
    raise exception 'Stopped: the catalog tables of this app are missing.';
  end if;

  -- Brands
  insert into public.brands (name)
  select distinct on (lower(s.brand)) s.brand
  from jsonb_to_recordset(v_data) as s(brand text, model text, year integer, variants jsonb, colors jsonb)
  where not exists (select 1 from public.brands b where lower(b.name) = lower(s.brand))
  order by lower(s.brand), s.brand
  on conflict do nothing;
  get diagnostics v_brands = row_count;

  -- Models (phones)
  insert into public.product_models (brand_id, name, product_type, release_year)
  select b.id, s.model, 'phone', s.year
  from jsonb_to_recordset(v_data) as s(brand text, model text, year integer, variants jsonb, colors jsonb)
  join public.brands b on lower(b.name) = lower(s.brand)
  where not exists (select 1 from public.product_models pm
                    where pm.brand_id = b.id and lower(pm.name) = lower(s.model))
  on conflict do nothing;
  get diagnostics v_models = row_count;

  -- Storage / RAM options
  insert into public.model_variants (model_id, storage_gb, ram_gb)
  select pm.id, v.storage_gb, v.ram_gb
  from jsonb_to_recordset(v_data) as s(brand text, model text, year integer, variants jsonb, colors jsonb)
  join public.brands b on lower(b.name) = lower(s.brand)
  join public.product_models pm on pm.brand_id = b.id and lower(pm.name) = lower(s.model)
  cross join lateral jsonb_to_recordset(s.variants) as v(storage_gb integer, ram_gb integer)
  on conflict do nothing;
  get diagnostics v_variants = row_count;

  -- Colours
  insert into public.model_colors (model_id, name)
  select pm.id, c.name
  from jsonb_to_recordset(v_data) as s(brand text, model text, year integer, variants jsonb, colors jsonb)
  join public.brands b on lower(b.name) = lower(s.brand)
  join public.product_models pm on pm.brand_id = b.id and lower(pm.name) = lower(s.model)
  cross join lateral jsonb_array_elements_text(s.colors) as c(name)
  on conflict do nothing;
  get diagnostics v_colors = row_count;

  raise notice 'Phone catalog seed: added % brands, % models, % storage options, % colours.',
    v_brands, v_models, v_variants, v_colors;
end;
$seed$;

-- What the catalog holds now
select (select count(*) from public.brands) as brands,
       (select count(*) from public.product_models) as models,
       (select count(*) from public.model_variants) as storage_options,
       (select count(*) from public.model_colors) as colours;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sql, "utf8");
console.log(
  `Wrote ${outFile}: ${brands.size} brands, ${models.length} models, ${variantCount} variants, ${colorCount} colours`
);
